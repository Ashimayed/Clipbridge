// Builds the shared test vectors from the Chrome extension's implementation.
// The Android core module (android-app/core) must reproduce every value byte for byte.
import * as C from '../chrome-extension/crypto.js';
import * as L from '../chrome-extension/logic.js';

const hex = (b) => [...b].map((x) => x.toString(16).padStart(2, '0')).join('');
export const unhex = (h) => new Uint8Array(h.match(/../g)?.map((x) => parseInt(x, 16)) ?? []);
const sha = async (b) => hex(new Uint8Array(await crypto.subtle.digest('SHA-256', b)));

/** Deterministic plaintext: byte i = (i * 31 + 7) mod 256. */
export const pattern = (n) => { const b = new Uint8Array(n); for (let i = 0; i < n; i++) b[i] = (i * 31 + 7) & 255; return b; };

const KEY = '000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f';
const PREFIX = 'a1b2c3d4e5f60718';

export async function buildVectors() {
  const v = { format: 'CB1', note: 'Generated by tests/gen-vectors.mjs. Both apps must match every value exactly.' };

  v.pbkdf2 = [];
  for (const [passphrase, email, iterations] of [
    ['correct horse battery staple', 'someone@example.com', 1000],
    ['  Pässwörd with ünïcödé ✓ 🔑  ', '  MixedCase@Example.COM \n', 2000],
    ['purple couch tuesday', 'a+b@gmail.com', C.ITERATIONS],
  ]) {
    const key = await C.deriveKey(passphrase, email, iterations);
    v.pbkdf2.push({ passphrase, email, iterations, key: hex(key), keyCheck: await C.keyCheck(key) });
  }

  v.content = [];
  const key = await C.importKey(unhex(KEY));
  for (const size of [0, 1, 37, C.CHUNK - 1, C.CHUNK, C.CHUNK + 1, 3 * C.CHUNK + 1234]) {
    const ct = await C.encryptBytes(key, unhex(PREFIX), pattern(size));
    v.content.push({ key: KEY, prefix: PREFIX, plainSize: size, cipherLength: ct.length,
      cipherSha256: await sha(ct), ...(size <= 64 ? { cipher: hex(ct) } : {}) });
  }

  v.headers = [];
  for (const h of [
    { name: 'clip.txt', mime: 'text/plain', kind: 'text', device: 'Chrome on Windows', size: 12 },
    { name: 'Holiday photo (1).JPG', mime: 'image/jpeg', kind: 'image', device: 'Pixel 9 Pro', size: 4194304 },
    { name: 'report "final" \\ v2/3.pdf', mime: 'application/pdf', kind: 'file', device: 'Work laptop', size: 0 },
    { name: 'tab\there\nnew\rline\u0001\u001f\u007f', mime: 'application/octet-stream', kind: 'file', device: 'Ünïcödé 📱', size: 9007199254740991 },
    { name: 'line sep  <b>&amp;</b>', mime: 'text/html', kind: 'file', device: '', size: 5 },
    { name: 'lone \ud800 high, lone \udc00 low, pair 😀', mime: 'image/png', kind: 'image', device: 'x', size: 1 },
  ]) {
    const description = await C.sealHeader(key, unhex(PREFIX), h);
    v.headers.push({ key: KEY, prefix: PREFIX, header: h, json: JSON.stringify({ n: h.name, m: h.mime, k: h.kind, d: h.device, s: h.size }), description });
  }

  v.pairing = [];
  for (const email of ['someone@example.com', ' A.B+tag@Example.com ', "o'brien~*(x)!@mail.co"]) {
    const s = await L.buildPairing(unhex(KEY), email);
    v.pairing.push({ key: KEY, email, code: s, parsed: await L.parsePairing(s).then((r) => ({ ok: r.ok, check: r.check, email: r.email })) });
  }
  v.pairingBad = [];
  const good = v.pairing[0].code;
  for (const input of [
    '', 'https://example.com', 'clipbridge://pair?v=2&k=x&c=y&e=z', good.replace('v=1', 'v=1&v=1'),
    good.replace(/k=[^&]+/, 'k=AAAA'), good.replace(/c=[^&]+/, 'c=0000-0000'), good.replace(/e=[^&]+/, 'e=nobody'),
    good + '%', 'clipbridge://pair?' + 'x'.repeat(400), good.replace(/e=[^&]+/, 'e=a+b%40c.de'),
  ]) {
    const r = await L.parsePairing(input);
    v.pairingBad.push({ input, ok: r.ok, ...(r.ok ? { email: r.email } : { reason: r.reason }) });
  }

  v.redact = [
    'Signed in as person.name+tag@example.co.uk', 'Authorization: Bearer ya29.a0AfH6SMBxxxxxxxxxxxxxxxxxxxxxxxxx',
    'GET https://www.googleapis.com/drive/v3/files?q=secret&key=abc ok', 'id 1AbCdEfGhIjKlMnOpQrStUvWxYz0123456789 gone',
    '  lots   of\n\twhite\r\nspace  ', 'x'.repeat(400), 'short-id abcdefghij0123456789abcdefg (27 chars) stays',
  ].map((input) => ({ input, output: L.redact(input) }));
  v.redactMax = [{ input: 'é'.repeat(20), max: 10, output: L.redact('é'.repeat(20), 10) }];

  v.poll = [];
  for (const mode of ['instant', 'balanced', 'saver', 'bogus']) {
    for (const idleMs of [-5, 0, 29999, 30000, 119999, 120000, 599999, 600000, 86400000]) {
      v.poll.push({ mode, idleMs, intervalMs: L.pollIntervalMs(mode, idleMs) });
    }
  }
  v.jitter = [[3000, 0], [3000, 0.5], [3000, 0.999999], [3000, 1], [3000, -1], [45000, 0.123456], [20000, 0.987]]
    .map(([ms, unit]) => ({ ms, unit, output: L.jittered(ms, unit) }));

  const items = [
    { id: 'a', createdTime: '2026-01-01T00:00:01.000Z', pinned: false },
    { id: 'b', createdTime: '2026-01-01T00:00:02.000Z', pinned: true },
    { id: 'c', createdTime: '2026-01-01T00:00:03.000Z', pinned: false },
    { id: 'e', createdTime: '2026-01-01T00:00:03.000Z', pinned: false },
    { id: 'd', createdTime: '2026-01-01T00:00:04.000Z', pinned: false },
    { id: 'f', createdTime: '2026-01-01T00:00:00.500Z', pinned: true },
  ];
  v.prune = [0, 1, 2, 3, 10].map((keep) => ({ items, keep, delete: L.planPrune(items, keep) }));

  v.safeName = ['photo.jpg', '../../etc/passwd', '..', '...', '', '   ', 'a:b*c?d"e<f>g|h\\i/j', 'tab\tname\u0001.txt',
    '﻿ bom name  ', 'x'.repeat(130) + '.txt', '  spaced  .pdf  ', 'ok name']
    .map((input) => ({ input, output: L.safeName(input) }));

  v.deviceName = ['Work laptop', '  Work \t laptop  ', '', '   ', 'tab\tnew\nline\u0000\u007f\u0085x',
    'a'.repeat(39) + '😀' + 'b', 'a'.repeat(50), 'nb sp em﻿bom', '　Full width　']
    .map((input) => ({ input, output: L.cleanDeviceName(input) }));

  v.sha256Text = ['', 'hello', 'line1\r\nline2\r\n', 'mixed\rcr\nlf', 'ünïcödé 😀']
    .map((input) => ({ input, output: null }));
  const { sha256Text } = await import('../chrome-extension/drive.js');
  for (const t of v.sha256Text) t.output = await sha256Text(t.input);

  return v;
}
